-- Orçamento manual ZapERP × API WM (ERP Icthus) — persistência local.
-- Fonte normativa do plano: docs/ai-handoff/36-ORCAMENTO-WM-INTEGRACAO.md (seções 6 e 7).
-- Sessão 2A: fundação desligada. Nenhuma rota montada, WM_ORCAMENTOS_ENABLED=false.
--
-- Duas tabelas, nenhuma coluna cifrada (decisão D1 do doc 36): não existe um único
-- `createCipheriv` nesta codebase, e cifrar só o telefone enquanto todo o resto está em texto
-- é teatro com risco operacional real. A proteção do telefone autorizado é de ACESSO:
-- SERVICE_ROLE só, nunca em resposta de API (só `telefone_ultimos4`), nunca em log.
--
-- ATENÇÃO multitenancy: o cliente Supabase do backend usa SERVICE_ROLE e BYPASSA RLS.
-- O `ENABLE ROW LEVEL SECURITY` abaixo é defesa em profundidade contra acesso por anon/
-- authenticated — NÃO substitui o `.eq('company_id', …)` obrigatório em toda query do backend.

-- =========================================================
-- 1. CONFIGURAÇÃO POR EMPRESA (vínculo com o contato autorizado da WM)
-- =========================================================
-- Uma linha por empresa. `telefone_autorizado` NÃO é o telefone da conversa nem o do
-- comprador: é o contato que resolve a instalação/empresa do lado da WM (seção 4 do doc 36).
-- Confundir os dois é o maior risco de isolamento desta integração.
--
-- Provisionado por operação/suporte confiável, não por admin de tenant: a validação da WM
-- devolve só `{ autorizado: true }`, o que prova que o telefone é aceito — não que pertence
-- à mesma empresa do `company_id` do ZapERP (pendência 13 da seção 10).
CREATE TABLE IF NOT EXISTS public.wm_orcamento_integracoes (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           integer NOT NULL UNIQUE REFERENCES public.empresas(id) ON DELETE CASCADE,
  ativo                boolean NOT NULL DEFAULT false,
  telefone_autorizado  text,
  telefone_ultimos4    varchar(4),
  validado_em          timestamptz,
  validacao_status     text NOT NULL DEFAULT 'nao_validado'
                         CHECK (validacao_status IN ('nao_validado','autorizado','negado','erro')),
  provisionado_por     text,
  criado_em            timestamptz NOT NULL DEFAULT now(),
  atualizado_em        timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.wm_orcamento_integracoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.wm_orcamento_integracoes FROM anon, authenticated;
GRANT ALL ON public.wm_orcamento_integracoes TO service_role;

COMMENT ON TABLE public.wm_orcamento_integracoes IS
  'Vínculo da empresa com a API WM. Uma linha por company_id. Ler sempre com .eq(company_id).';
COMMENT ON COLUMN public.wm_orcamento_integracoes.ativo IS
  'Gate POR EMPRESA. A flag efetiva é esta E a env global WM_ORCAMENTOS_ENABLED (helpers/orcamentoWmFlag.js).';
COMMENT ON COLUMN public.wm_orcamento_integracoes.telefone_autorizado IS
  'Segredo operacional. Contato autorizado da WM (NÃO o telefone da conversa nem o do comprador). Nunca expor em respostas, nunca logar — só telefone_ultimos4 sai do servidor.';
COMMENT ON COLUMN public.wm_orcamento_integracoes.telefone_ultimos4 IS
  'Últimos 4 dígitos, único recorte exibível do telefone autorizado.';
COMMENT ON COLUMN public.wm_orcamento_integracoes.provisionado_por IS
  'Quem provisionou o vínculo (operação/suporte). Texto livre para rastreio, sem dado pessoal.';

-- =========================================================
-- 2. OPERAÇÕES DE ORÇAMENTO (preparação → criação)
-- =========================================================
-- `id` é o identificador da PREPARAÇÃO devolvido ao navegador (opaco).
-- `comando_id` é gerado pelo BACKEND, uma única vez por confirmação de negócio, e persistido
-- ANTES da chamada externa. O frontend nunca gera UUID. Duplo clique, duas abas, F5 ou timeout
-- não criam outro comando — a trava é a transição atômica de estado (seção 7 do doc 36):
--
--   UPDATE wm_orcamento_operacoes
--      SET estado='ENVIANDO', comando_id=$uuid, enviado_em=now()
--    WHERE id=$preparacao_id AND company_id=$jwt AND estado='PREPARADO' AND expira_em > now()
--
-- `payload_criacao` guarda o payload exato da criação (snapshot server-side do preço: a UI
-- nunca devolve preço) e `payload_hash` é o SHA-256 do JSON canônico — basta para detectar
-- "mesmo comando_id, payload diferente", que é erro crítico local e nunca é despachado (D4).
CREATE TABLE IF NOT EXISTS public.wm_orcamento_operacoes (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id               integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  usuario_id               integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  conversa_id              integer REFERENCES public.conversas(id) ON DELETE SET NULL,

  estado                   text NOT NULL DEFAULT 'PREPARADO'
                             CHECK (estado IN (
                               'PREPARADO','ENVIANDO','CRIADO','FALHA_SEGURA','INCERTO','EXPIRADO'
                             )),

  comando_id               uuid,
  payload_criacao          jsonb,
  payload_hash             text,
  previa_sanitizada        jsonb,
  wm_resultado_sanitizado  jsonb,

  http_status_ultimo       integer,
  erro_codigo_ultimo       text,
  tentativas               integer NOT NULL DEFAULT 0,

  expira_em                timestamptz,
  enviado_em               timestamptz,
  concluido_em             timestamptz,
  criado_em                timestamptz NOT NULL DEFAULT now(),
  atualizado_em            timestamptz NOT NULL DEFAULT now()
);

-- Histórico da empresa (tela de orçamentos) e histórico dentro de uma conversa.
CREATE INDEX IF NOT EXISTS idx_wm_orcamento_operacoes_company
  ON public.wm_orcamento_operacoes (company_id, criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wm_orcamento_operacoes_conversa
  ON public.wm_orcamento_operacoes (company_id, conversa_id, criado_em DESC);

-- Idempotência: um comando_id no sistema inteiro. Parcial porque preparação ainda não
-- confirmada tem comando_id NULL (e NULL não colide em UNIQUE, mas o índice parcial deixa
-- a intenção explícita e não indexa as preparações abandonadas).
CREATE UNIQUE INDEX IF NOT EXISTS uq_wm_orcamento_operacoes_comando
  ON public.wm_orcamento_operacoes (comando_id)
  WHERE comando_id IS NOT NULL;

-- Varreduras por estado (expirar PREPARADO vencido, listar INCERTO para o runbook de suporte).
CREATE INDEX IF NOT EXISTS idx_wm_orcamento_operacoes_estado
  ON public.wm_orcamento_operacoes (company_id, estado);

ALTER TABLE public.wm_orcamento_operacoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.wm_orcamento_operacoes FROM anon, authenticated;
GRANT ALL ON public.wm_orcamento_operacoes TO service_role;

COMMENT ON TABLE public.wm_orcamento_operacoes IS
  'Preparações e criações de orçamento WM. O id é a preparação; o comando_id é a idempotência da criação.';
COMMENT ON COLUMN public.wm_orcamento_operacoes.estado IS
  'PREPARADO→ENVIANDO→{CRIADO|FALHA_SEGURA|INCERTO}; PREPARADO→EXPIRADO. INCERTO é TERMINAL (D10): nunca gerar comando_id novo para "corrigir".';
COMMENT ON COLUMN public.wm_orcamento_operacoes.comando_id IS
  'Gerado pelo backend e persistido ANTES do despacho. Nunca vem do navegador, nunca é regerado.';
COMMENT ON COLUMN public.wm_orcamento_operacoes.payload_criacao IS
  'Snapshot server-side do payload de criação (inclui o preço oficial da preparação). Nunca ecoar ao navegador nem logar inteiro. Limpar após a janela de idempotência da WM.';
COMMENT ON COLUMN public.wm_orcamento_operacoes.payload_hash IS
  'SHA-256 do JSON canônico de payload_criacao. Mesmo comando_id com hash diferente = erro crítico local.';
COMMENT ON COLUMN public.wm_orcamento_operacoes.previa_sanitizada IS
  'Prévia exibível ao atendente. Sem CPF/CNPJ/IE de candidatos não selecionados.';
