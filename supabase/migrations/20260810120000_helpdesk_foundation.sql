REVOKE ALL ON public.helpdesk_mensagens FROM anon, authenticated;
REVOKE ALL ON public.helpdesk_transferencias FROM anon, authenticated;
GRANT ALL ON public.helpdesk_tickets TO service_role;
GRANT ALL ON public.helpdesk_mensagens TO service_role;
GRANT ALL ON public.helpdesk_transferencias TO service_role;
