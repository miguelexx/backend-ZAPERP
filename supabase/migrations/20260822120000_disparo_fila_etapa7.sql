-- =========================================================
-- 7. RPC: claim atômico com SKIP LOCKED
-- =========================================================
CREATE OR REPLACE FUNCTION public.disparo_claim_fila_itens(
  p_worker_id text,
  p_limit integer DEFAULT 5,
  p_lease_seconds integer DEFAULT 120,
  p_instancia_id integer DEFAULT NULL
)
RETURNS SETOF public.disparo_fila_itens
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_limit integer := GREATEST(1, LEAST(COALESCE(p_limit, 5), 50));
  v_lease interval := make_interval(secs => GREATEST(30, LEAST(COALESCE(p_lease_seconds, 120), 900)));
BEGIN
  IF p_worker_id IS NULL OR length(trim(p_worker_id)) = 0 THEN
    RAISE EXCEPTION 'worker_id obrigatório';
  END IF;

  RETURN QUERY
  WITH candidatos AS (
    SELECT f.id
    FROM public.disparo_fila_itens f
    INNER JOIN public.disparo_execucoes e ON e.id = f.execucao_id
    WHERE f.status = 'pendente'
      AND f.proxima_tentativa_em <= now()
      AND e.status = 'em_execucao'
      AND (p_instancia_id IS NULL OR f.instancia_id = p_instancia_id)
    ORDER BY f.proxima_tentativa_em ASC, f.id ASC
    FOR UPDATE OF f SKIP LOCKED
    LIMIT v_limit
  )
  UPDATE public.disparo_fila_itens f
  SET
    status = 'reservada',
    worker_id = p_worker_id,
    lease_inicio = now(),
    lease_ate = now() + v_lease,
    atualizado_em = now()
  FROM candidatos c
  WHERE f.id = c.id
  RETURNING f.*;
END;
$$;

REVOKE ALL ON FUNCTION public.disparo_claim_fila_itens(text, integer, integer, integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.disparo_claim_fila_itens(text, integer, integer, integer) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.disparo_claim_fila_itens(text, integer, integer, integer) TO service_role;

-- Recupera leases expirados (reservada/enviando → pendente)
CREATE OR REPLACE FUNCTION public.disparo_recuperar_leases_expirados(
  p_limit integer DEFAULT 100
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count integer;
BEGIN
  WITH upd AS (
    UPDATE public.disparo_fila_itens
    SET
      status = 'pendente',
      worker_id = NULL,
      lease_inicio = NULL,
      lease_ate = NULL,
      atualizado_em = now(),
      proxima_tentativa_em = now()
    WHERE id IN (
      SELECT id FROM public.disparo_fila_itens
      WHERE status IN ('reservada', 'enviando')
        AND lease_ate IS NOT NULL
        AND lease_ate < now()
      ORDER BY lease_ate ASC
      FOR UPDATE SKIP LOCKED
      LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 100), 500))
    )
    RETURNING id
  )
  SELECT COUNT(*)::integer INTO v_count FROM upd;
  RETURN COALESCE(v_count, 0);
END;
$$;

REVOKE ALL ON FUNCTION public.disparo_recuperar_leases_expirados(integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.disparo_recuperar_leases_expirados(integer) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.disparo_recuperar_leases_expirados(integer) TO service_role;

-- Advisory lock por instância (key namespace: disparo_inst:{id})
CREATE OR REPLACE FUNCTION public.disparo_try_lock_instancia(p_instancia_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_instancia_id IS NULL OR p_instancia_id <= 0 THEN
    RETURN false;
  END IF;
  RETURN pg_try_advisory_lock(872014, p_instancia_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.disparo_unlock_instancia(p_instancia_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_instancia_id IS NULL OR p_instancia_id <= 0 THEN
    RETURN false;
  END IF;
  RETURN pg_advisory_unlock(872014, p_instancia_id);
END;
$$;

REVOKE ALL ON FUNCTION public.disparo_try_lock_instancia(integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.disparo_unlock_instancia(integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.disparo_try_lock_instancia(integer) FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.disparo_unlock_instancia(integer) FROM anon, authenticated;
