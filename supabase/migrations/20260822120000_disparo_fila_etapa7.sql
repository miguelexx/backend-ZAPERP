-- Etapa 7: fila persistente, execuções, exclusões e claim atômico (SKIP LOCKED).
-- Sem Redis. Envio real permanece controlado por feature flags no app (default off).

-- =========================================================
-- 1. LISTA DE EXCLUSÃO (por empresa)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.disparo_exclusoes (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id            integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  telefone_normalizado  varchar(20) NOT NULL,
  telefone_original     varchar(30),
  motivo                text,
  origem                text NOT NULL DEFAULT 'manual'
                          CHECK (origem IN ('manual','importacao','optout','sistema')),
  ativo                 boolean NOT NULL DEFAULT true,
  criado_por            integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  criado_em             timestamptz NOT NULL DEFAULT now(),
  removido_por          integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  removido_em           timestamptz,
  CONSTRAINT disparo_exclusoes_unique UNIQUE (company_id, telefone_normalizado)
);

CREATE INDEX IF NOT EXISTS idx_disparo_exclusoes_company_ativo
  ON public.disparo_exclusoes (company_id, ativo)
  WHERE ativo = true;

ALTER TABLE public.disparo_exclusoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.disparo_exclusoes FROM anon, authenticated;
GRANT ALL ON public.disparo_exclusoes TO service_role;

-- =========================================================
-- 2. EXECUÇÕES DA CAMPANHA
-- =========================================================
CREATE TABLE IF NOT EXISTS public.disparo_execucoes (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id            integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  campanha_id           bigint  NOT NULL REFERENCES public.disparo_campanhas(id) ON DELETE CASCADE,
  revisao_id            bigint  REFERENCES public.disparo_campanha_revisoes(id) ON DELETE SET NULL,
  versao                integer NOT NULL,
  config_hash           text NOT NULL,

  status                text NOT NULL DEFAULT 'aguardando'
                          CHECK (status IN (
                            'aguardando','em_execucao','pausada','concluida','cancelada','emergencia'
                          )),
  motivo_pausa          text,
  tipo_pausa            text
                          CHECK (tipo_pausa IS NULL OR tipo_pausa IN (
                            'manual','operacional','limite','horario','erro','desconexao','emergencia','data_limite'
                          )),

  iniciado_em           timestamptz,
  finalizado_em         timestamptz,
  iniciado_por          integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  pausado_por           integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  cancelado_por         integer REFERENCES public.usuarios(id) ON DELETE SET NULL,

  total_itens           integer NOT NULL DEFAULT 0,
  total_enviados        integer NOT NULL DEFAULT 0,
  total_entregues       integer NOT NULL DEFAULT 0,
  total_lidos           integer NOT NULL DEFAULT 0,
  total_falhas          integer NOT NULL DEFAULT 0,
  total_incertos        integer NOT NULL DEFAULT 0,
  total_ignorados       integer NOT NULL DEFAULT 0,
  total_cancelados      integer NOT NULL DEFAULT 0,

  dry_run               boolean NOT NULL DEFAULT true,
  criado_em             timestamptz NOT NULL DEFAULT now(),
  atualizado_em         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_disparo_execucoes_campanha
  ON public.disparo_execucoes (company_id, campanha_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_disparo_execucoes_status
  ON public.disparo_execucoes (company_id, status)
  WHERE status IN ('aguardando','em_execucao','pausada');

ALTER TABLE public.disparo_execucoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.disparo_execucoes FROM anon, authenticated;
GRANT ALL ON public.disparo_execucoes TO service_role;

