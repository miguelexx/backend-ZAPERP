-- Ranking gamificado de atendentes (competição semanal).
-- Doc: docs/ai-handoff/42-RANKING-GAMIFICADO.md
--
-- ADITIVA E SEGURA: só cria duas tabelas novas. Não altera nenhuma tabela existente,
-- não toca em `atendimentos` (fonte da contagem) e não muda nenhum fluxo de atendimento.
--
-- A CONTAGEM NÃO MORA AQUI. O ranking conta as linhas de `atendimentos` com
-- acao = 'encerrou' por `de_usuario_id` — a mesma regra do "Finalizadas hoje" da Supervisão
-- (services/supervisaoService.js). Esta migration guarda apenas:
--   1) a configuração da competição por empresa;
--   2) os ciclos (o em andamento + o resultado CONSOLIDADO dos encerrados), para que
--      apagar/mexer em atendimentos depois do encerramento não altere um resultado já fechado.
--
-- ATENÇÃO multitenancy: o backend usa SERVICE_ROLE (bypassa RLS). O RLS abaixo é defesa em
-- profundidade contra anon/authenticated — NÃO substitui o .eq('company_id', …) do código.
--
-- Ordem de deploy: aplicar ANTES do código. Mesmo assim o código tolera a tabela ausente
-- (ranking aparece como desligado e o agendador só registra um aviso).

-- =========================================================
-- 1. CONFIGURAÇÃO POR EMPRESA
-- =========================================================
CREATE TABLE IF NOT EXISTS public.ranking_config (
  company_id     integer PRIMARY KEY REFERENCES public.empresas(id) ON DELETE CASCADE,
  ativo          boolean  NOT NULL DEFAULT false,
  -- 0 = domingo … 6 = sábado (mesma convenção de Date#getDay / helpers/businessSchedule.js)
  dia_semana     smallint NOT NULL DEFAULT 5 CHECK (dia_semana BETWEEN 0 AND 6),
  -- 'HH:MM' no fuso da empresa (ia_config.config.chatbot_triage.timezone)
  horario        text     NOT NULL DEFAULT '18:00' CHECK (horario ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  atualizado_por integer  REFERENCES public.usuarios(id) ON DELETE SET NULL,
  criado_em      timestamptz NOT NULL DEFAULT now(),
  atualizado_em  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.ranking_config ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ranking_config FROM anon, authenticated;
GRANT ALL ON public.ranking_config TO service_role;

COMMENT ON TABLE public.ranking_config IS
  'Configuração do ranking gamificado. Uma linha por empresa. Mudanças valem para o PRÓXIMO ciclo.';

-- =========================================================
-- 2. CICLOS DA COMPETIÇÃO
-- =========================================================
-- Intervalo semiaberto [inicio, fim): um atendimento encerrado exatamente em `fim` já é do
-- ciclo seguinte (que começa em `fim`). Assim os ciclos nunca se sobrepõem.
CREATE TABLE IF NOT EXISTS public.ranking_ciclos (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  inicio              timestamptz NOT NULL,
  fim                 timestamptz NOT NULL,
  -- regra congelada no nascimento do ciclo (mudar a config não mexe no ciclo em andamento)
  timezone            text     NOT NULL,
  dia_semana          smallint NOT NULL,
  horario             text     NOT NULL,
  status              text     NOT NULL DEFAULT 'em_andamento'
                        CHECK (status IN ('em_andamento', 'encerrado', 'cancelado')),
  -- resultado consolidado no encerramento (snapshot: nome + total por atendente)
  classificacao       jsonb,
  vencedores          jsonb,
  total_vencedor      integer,
  total_atendimentos  integer,
  encerrado_em        timestamptz,
  criado_em           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ranking_ciclos_intervalo_valido CHECK (fim > inicio)
);

-- Trava de concorrência: no máximo UM ciclo em andamento por empresa (reinício, duas
-- instâncias ou clique duplo não criam ciclos paralelos).
CREATE UNIQUE INDEX IF NOT EXISTS ux_ranking_ciclos_em_andamento
  ON public.ranking_ciclos (company_id)
  WHERE status = 'em_andamento';

-- Histórico: lista os encerrados mais recentes da empresa.
CREATE INDEX IF NOT EXISTS idx_ranking_ciclos_company_fim
  ON public.ranking_ciclos (company_id, fim DESC);

ALTER TABLE public.ranking_ciclos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ranking_ciclos FROM anon, authenticated;
GRANT ALL ON public.ranking_ciclos TO service_role;

COMMENT ON TABLE public.ranking_ciclos IS
  'Ciclos do ranking gamificado. em_andamento conta ao vivo; encerrado guarda o resultado consolidado. Ler sempre com .eq(company_id).';
