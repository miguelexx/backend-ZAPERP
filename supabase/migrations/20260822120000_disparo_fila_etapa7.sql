  variacao_id             bigint  NOT NULL REFERENCES public.disparo_campanha_variacoes(id) ON DELETE RESTRICT,

  status                  text NOT NULL DEFAULT 'pendente'
                            CHECK (status IN (
                              'pendente','reservada','enviando','enviada','entregue','lida',
                              'falhou','incerta','ignorada','cancelada'
                            )),
  tentativas              integer NOT NULL DEFAULT 0,
